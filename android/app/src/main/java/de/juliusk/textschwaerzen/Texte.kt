    private val kataloge = mapOf("de" to de, "en" to en, "fr" to fr, "es" to es, "zh" to zh)

    /** Sprache der Oberfläche: die Systemsprache, sonst Englisch. */
    val sprache: String = run {
        val gewaehlt = Locale.getDefault().language.lowercase()
        if (kataloge.containsKey(gewaehlt)) gewaehlt else "en"
    }

    /** Text zu einem Schlüssel — fehlt er, kommt der Schlüssel selbst (nie leer). */
    fun t(schluessel: String): String =
        kataloge[sprache]?.get(schluessel) ?: en[schluessel] ?: schluessel
